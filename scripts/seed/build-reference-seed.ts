// Generates the production-safe reference data migration (markets with Census county boundaries,
// services, prices and fees) from supabase/data/*.json. Re-run after editing the data files:
//   node scripts/seed/build-reference-seed.ts
// Reference data only: no fake providers, requests or people (those live in supabase/seed.sql, dev only).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type Feature = { properties: { GEOID: string; NAME: string }; geometry: unknown };
type Market = {
  slug: string;
  name: string;
  stateCode: string;
  timeZone: string;
  status: string;
  center: [number, number];
  counties: string[];
};
type Service = {
  slug: string;
  name: string;
  description: string;
  iconKey: string;
  needsDestination: boolean;
  vehicles: string[];
  sortOrder: number;
  priceMinCents: number | null;
  priceMaxCents: number | null;
  priceNote: string | null;
  feeCents: number | null;
  enabled: boolean;
};

const root = (p: string) => fileURLToPath(new URL(`../../${p}`, import.meta.url));
const counties = JSON.parse(
  readFileSync(root("supabase/data/census-counties-2024-500k.geojson"), "utf8"),
) as { features: Feature[] };
const data = JSON.parse(readFileSync(root("supabase/data/markets.json"), "utf8")) as {
  effectiveFrom: string;
  markets: Market[];
  services: Service[];
};

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null) => (v === null ? "null" : String(v));
const byGeoid = new Map(counties.features.map((f) => [f.properties.GEOID, f]));

const countyRows = data.markets.flatMap((m) =>
  m.counties.map((geoid) => {
    const f = byGeoid.get(geoid);
    if (!f) throw new Error(`County ${geoid} missing from the Census file`);
    return `  (${q(m.slug)}, ${q(geoid)}, ${q(f.properties.NAME)}, extensions.st_setsrid(extensions.st_geomfromgeojson(${q(JSON.stringify(f.geometry))}), 4326))`;
  }),
);

const sql = `-- GENERATED by scripts/seed/build-reference-seed.ts from supabase/data. Do not edit by hand.
-- RSOS-017: production-safe reference data for every environment (dev, staging, production):
-- the six services, five markets with US Census county boundaries (ACS 2024, 1:500k cartographic),
-- and dated prices and platform fees. Idempotent: existing rows are left untouched.

insert into public.services (slug, name, description, icon_key, needs_destination, allowed_vehicle_types, sort_order) values
${data.services
  .map(
    (s) =>
      `  (${q(s.slug)}, ${q(s.name)}, ${q(s.description)}, ${q(s.iconKey)}, ${s.needsDestination}, array[${s.vehicles.map(q).join(", ")}]::public.vehicle_type[], ${s.sortOrder})`,
  )
  .join(",\n")}
on conflict (slug) do nothing;

create temporary table seed_counties (market_slug text, geoid text, name text, geom extensions.geometry) on commit drop;
insert into seed_counties values
${countyRows.join(",\n")};

insert into public.markets (slug, name, state_code, time_zone, center, boundary, status)
select v.slug, v.name, v.state_code, v.time_zone,
       extensions.st_setsrid(extensions.st_makepoint(v.lng, v.lat), 4326)::extensions.geography,
       (select extensions.st_multi(extensions.st_makevalid(extensions.st_union(c.geom)))::extensions.geography from seed_counties c where c.market_slug = v.slug),
       v.status::public.market_status
from (values
${data.markets.map((m) => `  (${q(m.slug)}, ${q(m.name)}, ${q(m.stateCode)}, ${q(m.timeZone)}, ${m.center[0]}::double precision, ${m.center[1]}::double precision, ${q(m.status)})`).join(",\n")}
) as v(slug, name, state_code, time_zone, lat, lng, status)
on conflict (slug) do nothing;

insert into public.market_services (market_id, service_id, enabled, price_min_cents, price_max_cents, price_note, platform_fee_cents, effective_from)
select m.id, s.id, p.enabled, p.price_min_cents, p.price_max_cents, p.price_note, p.platform_fee_cents, ${q(data.effectiveFrom)}::timestamptz
from public.markets m
cross join (values
${data.services.map((s) => `  (${q(s.slug)}, ${s.enabled}, ${n(s.priceMinCents)}::integer, ${n(s.priceMaxCents)}::integer, ${q(s.priceNote)}, ${n(s.feeCents)}::integer)`).join(",\n")}
) as p(service_slug, enabled, price_min_cents, price_max_cents, price_note, platform_fee_cents)
join public.services s on s.slug = p.service_slug::extensions.citext
where m.slug in (${data.markets.map((m) => q(m.slug)).join(", ")})
on conflict (market_id, service_id, effective_from) do nothing;
`;

const out = root("supabase/migrations/20261113030000_reference_data.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out} (${(sql.length / 1024).toFixed(0)} KB)`);
